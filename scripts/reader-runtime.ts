import assert from 'node:assert/strict';
import {
    createConnectorBundle,
    createSafeHttpClient,
    BROWSER_EXTRACTION_VERSION,
    pageFingerprint,
    ConnectorError,
} from '../packages/connectors/src/index.ts';

// Real Chromium + Crawlee against a controlled transport. No external websites or provider credentials.
let requests = 0;
let resourceStarted!: () => void;
const slowResource = new Promise<void>((resolve) => {
    resourceStarted = resolve;
});
const http = createSafeHttpClient({
    resolve: async () => [{ address: '93.184.216.34', family: 4 }],
    transport: async (url, options) => {
        requests++;
        if (url.pathname === '/slow.js') {
            resourceStarted();
            await new Promise((_, reject) =>
                options.signal.addEventListener('abort', () => reject(new Error('cancelled')), {
                    once: true,
                }),
            );
        }
        return {
            status: 200,
            headers: { 'content-type': 'text/html; charset=utf-8' },
            body: `<!doctype html><title>Runtime fixture</title><main id="root">Loading</main><script>document.getElementById('root').innerHTML='<article><h1>Rendered fixture</h1><p>CONTROLLED_DYNAMIC_READER_RUNTIME: this article is generated by JavaScript and collected through the actual default connector bundle.</p></article>';</script>${url.pathname === '/cancel' ? '<script src="/slow.js"></script>' : ''}`,
        };
    },
});
const bundle = createConnectorBundle({
    model: 'fixture-model',
    modelApiKey: 'fixture-key-never-dispatched',
    http,
});
const started = Date.now();
let reservations = 0;
try {
    assert.equal(requests, 0, 'construction must be offline');
    const page = await bundle.reader.read('https://fixture.example/article', {
        beforeAttempt: async (kind) => {
            assert.equal(kind, 'read');
            reservations++;
        },
    });
    assert(page.text.includes('CONTROLLED_DYNAMIC_READER_RUNTIME'));
    assert(!page.text.includes('Loading'));
    assert.equal(page.contentHash, pageFingerprint(page.text));
    assert.equal(page.extractionVersion, BROWSER_EXTRACTION_VERSION);
    assert.equal(page.untrusted, true);
    assert.equal(requests, 1);
    assert.equal(reservations, 1);
    const renderedMs = Date.now() - started;
    await assert.rejects(
        bundle.reader.read('https://fixture.example/denied', {
            beforeAttempt: () => {
                throw new ConnectorError('budget_exceeded', 'fixture denied');
            },
        }),
        { code: 'budget_exceeded' },
    );
    assert.equal(requests, 1, 'denied budget cannot dispatch HTTP');
    const cancelled = new AbortController();
    const pending = bundle.reader.read('https://fixture.example/cancel', {
        signal: cancelled.signal,
    });
    const settled = pending.then(
        () => null,
        (error) => error,
    );
    await Promise.race([
        slowResource,
        settled.then((error) => {
            throw error ?? new Error('missing slow resource');
        }),
    ]);
    cancelled.abort();
    assert.equal((await settled).code, 'aborted');
    await bundle.reader.close?.();
    assert.equal(requests, 3);
    console.log(
        JSON.stringify({
            runtime: process.versions.bun
                ? `bun ${process.versions.bun}`
                : `node ${process.versions.node}`,
            reader: 'crawlee-playwright',
            dynamicRendered: true,
            dynamicRequests: 1,
            requests,
            reservations,
            budgetDenied: true,
            inFlightCancelled: true,
            elapsedMs: renderedMs,
        }),
    );
} finally {
    await bundle.reader.close?.();
}
